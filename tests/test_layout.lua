local T = tile_test

T.test("computer, pocket, and minimum monitor grids", function()
  local layout = dofile("os/layout.lua")
  local computer = layout.metrics(51, 19)
  T.assertEq(computer.tooSmall, false)
  T.assertEq(computer.cols, 8)
  T.assertEq(computer.rows, 4)
  T.assertEq(computer.pageSize, 32)
  T.assertEq(computer.contentY, 2)

  local pocket = layout.metrics(26, 20)
  T.assertEq(pocket.cols, 4)
  T.assertEq(pocket.rows, 5)
  T.assertEq(pocket.pageSize, 20)

  local minimum = layout.metrics(15, 10)
  T.assertEq(minimum.cols, 2)
  T.assertEq(minimum.rows, 2)
  T.assertEq(minimum.pageSize, 4)

  local tiny = layout.metrics(7, 5)
  T.assertEq(tiny.tooSmall, true)
  T.assertEq(tiny.pageSize, 0)
  T.assertEq(layout.metrics(15, 9).tooSmall, true)
  T.assertEq(layout.metrics(14, 10).tooSmall, true)
end)

T.test("page count stays at one when there is nothing to page", function()
  local layout = dofile("os/layout.lua")
  T.assertEq(layout.pageCount(0, 32), 1)
  T.assertEq(layout.pageCount(32, 32), 1)
  T.assertEq(layout.pageCount(33, 32), 2)
  T.assertEq(layout.pageCount(4, 0), 1)
end)

T.test("clicks land on cells and miss the gaps", function()
  local layout = dofile("os/layout.lua")
  local metrics = layout.metrics(51, 19)
  T.assertEq(layout.hit(metrics, 1, 2, 1, 40), 1)
  T.assertEq(layout.hit(metrics, 5, 4, 1, 40), 1)
  T.assertEq(layout.hit(metrics, 6, 2, 1, 40), nil)
  T.assertEq(layout.hit(metrics, 1, 5, 1, 40), nil)
  T.assertEq(layout.hit(metrics, 7, 2, 1, 40), 2)
  T.assertEq(layout.hit(metrics, 1, 6, 1, 40), 9)
  T.assertEq(layout.hit(metrics, 1, 2, 2, 40), 33)
  T.assertEq(layout.hit(metrics, 1, 2, 1, 0), nil)
  local x, y = layout.cellOrigin(1, 0)
  T.assertEq(x, 7)
  T.assertEq(y, 2)
end)

T.test("the bar hit targets are Home and the page arrows", function()
  local layout = dofile("os/layout.lua")
  T.assertEq(layout.barHit(26, 1, 1, "app", 1), "home")
  T.assertEq(layout.barHit(26, 4, 1, "app", 1), "home")
  T.assertEq(layout.barHit(26, 5, 1, "app", 1), nil)
  T.assertEq(layout.barHit(26, 1, 1, "home", 2), nil)
  T.assertEq(layout.barHit(26, 24, 1, "home", 2), "prev")
  T.assertEq(layout.barHit(26, 25, 1, "home", 2), nil)
  T.assertEq(layout.barHit(26, 26, 1, "home", 2), "next")
  T.assertEq(layout.barHit(26, 26, 1, "home", 1), nil)
  T.assertEq(layout.tooSmallHit(1, 5), "use_computer")
  T.assertEq(layout.tooSmallHit(12, 5), "use_computer")
  T.assertEq(layout.tooSmallHit(13, 5), nil)
  T.assertEq(layout.tooSmallHit(1, 4), nil)
end)
